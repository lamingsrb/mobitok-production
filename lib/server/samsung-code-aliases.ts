const ima = (zapis: object, kljuc: string) => Object.prototype.hasOwnProperty.call(zapis, kljuc);

// Model iz adrese za upit bazi: alias vazi samo uz brend Samsung, jer isto ime kod drugog
// brenda ("A54 5G" kod Oppo) nije Samsung model. Nepoznat kljuc ostaje kakav jeste.
export function samsungModelAlias(
  deviceBrand: string | null | undefined,
  model: string | null,
  subcategory?: string | null,
): string | null {
  if (!model || deviceBrand !== "Samsung" || !ima(SAMSUNG_CODE_ALIASES, model)) return model;
  const osim = ima(SAMSUNG_ALIAS_OSIM_U, model) ? SAMSUNG_ALIAS_OSIM_U[model] : null;
  if (osim && (!subcategory || osim.includes(subcategory))) return model;
  return SAMSUNG_CODE_ALIASES[model];
}
